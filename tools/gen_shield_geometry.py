"""Generate ShieldGeometry.java from the imported shield item model.

The shield is drawn by our own SpecialModelRenderer, so the per face uvs of the Blockbench model
are baked here as a flat array of quads in Minecraft's centred model space
(0..16 item space minus the (8, 8, 8) origin, divided by 16).
"""
import json
import os

ROOT = "src/main/resources/assets/kalioupo_equipment"
OUT = "src/main/java/com/kalioupo/equipment/client/ShieldGeometry.java"

# same corner order the offline preview uses: bottom left, bottom right, top right, top left
FACES = {
    "north": lambda b: [(b["from"][0], b["from"][1], b["from"][2]),
                        (b["to"][0], b["from"][1], b["from"][2]),
                        (b["to"][0], b["to"][1], b["from"][2]),
                        (b["from"][0], b["to"][1], b["from"][2])],
    "south": lambda b: [(b["to"][0], b["from"][1], b["to"][2]),
                        (b["from"][0], b["from"][1], b["to"][2]),
                        (b["from"][0], b["to"][1], b["to"][2]),
                        (b["to"][0], b["to"][1], b["to"][2])],
    "east": lambda b: [(b["to"][0], b["from"][1], b["to"][2]),
                       (b["to"][0], b["from"][1], b["from"][2]),
                       (b["to"][0], b["to"][1], b["from"][2]),
                       (b["to"][0], b["to"][1], b["to"][2])],
    "west": lambda b: [(b["from"][0], b["from"][1], b["from"][2]),
                       (b["from"][0], b["from"][1], b["to"][2]),
                       (b["from"][0], b["to"][1], b["to"][2]),
                       (b["from"][0], b["to"][1], b["from"][2])],
    "up": lambda b: [(b["from"][0], b["to"][1], b["to"][2]),
                     (b["to"][0], b["to"][1], b["to"][2]),
                     (b["to"][0], b["to"][1], b["from"][2]),
                     (b["from"][0], b["to"][1], b["from"][2])],
    "down": lambda b: [(b["from"][0], b["from"][1], b["from"][2]),
                       (b["to"][0], b["from"][1], b["from"][2]),
                       (b["to"][0], b["from"][1], b["to"][2]),
                       (b["from"][0], b["from"][1], b["to"][2])],
}

NORMALS = {
    "north": (0, 0, -1), "south": (0, 0, 1),
    "east": (1, 0, 0), "west": (-1, 0, 0),
    "up": (0, 1, 0), "down": (0, -1, 0),
}

UV = {  # per corner, in the order above
    "north": [(0, 1), (1, 1), (1, 0), (0, 0)],
    "south": [(0, 1), (1, 1), (1, 0), (0, 0)],
    "east": [(0, 1), (1, 1), (1, 0), (0, 0)],
    "west": [(0, 1), (1, 1), (1, 0), (0, 0)],
    "up": [(0, 1), (1, 1), (1, 0), (0, 0)],
    "down": [(0, 1), (1, 1), (1, 0), (0, 0)],
}

HEADER = '''package com.kalioupo.equipment.client;

/**
 * Baked quads for the shield model, generated by {@code tools/gen_shield_geometry.py}.
 *
 * Coordinates are in centred model space: 0..16 item space minus the (8, 8, 8) origin, divided
 * by 16. Uvs are 0..1 for the 64x64 shield texture. Every quad is emitted twice by the renderer
 * (both windings) so the culled back face can not hide a wrongly wound face.
 */
public final class ShieldGeometry {
    /** 12 quads, each {nx, ny, nz, then 4 * (x, y, z, u, v)}. */
    public static final float[][] QUADS = {
'''


def main():
    with open(os.path.join(ROOT, "models/item/bedrock_shield.json"), encoding="utf-8") as f:
        model = json.load(f)

    lines = []

    for element in model["elements"]:
        for face, data in element["faces"].items():
            u1, v1, u2, v2 = data["uv"]
            normals = NORMALS[face]
            values = [normals[0], normals[1], -normals[2]]

            for corner, (u, v) in zip(FACES[face](element), UV[face]):
                x = (corner[0] - 8.0) / 16.0
                y = (corner[1] - 8.0) / 16.0
                # vanilla authors its shield model in entity space and undoes it with a
                # "scale": [1, -1, -1] in items/shield.json, so the z axis is mirrored here
                z = -(corner[2] - 8.0) / 16.0
                uu = (u1 + (u2 - u1) * u) / 16.0
                vv = (v1 + (v2 - v1) * v) / 16.0
                values += [x, y, z, uu, vv]

            body = ", ".join("%.5ff" % v for v in values)
            lines.append("            {%s}," % body)

    text = HEADER + "\n".join(lines) + "\n    };\n\n    private ShieldGeometry() {\n    }\n}\n"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)

    print("wrote", OUT, len(lines), "quads")


main()
